const ARABIC_DIGITS = ['٠','١','٢','٣','٤','٥','٦','٧','٨','٩'];

function t(key) {
  const lang = document.documentElement.lang || 'ar';
  return I18N[lang]?.[key] || I18N.en[key] || key;
}

function formatNumber(num, decimals = 1) {
  const numerals = localStorage.getItem('numerals') || 'western';
  let str = typeof num === 'number' ? num.toFixed(decimals) : String(num);
  if (numerals === 'arabic') {
    str = str.replace(/[0-9]/g, d => ARABIC_DIGITS[+d]);
  }
  return str;
}

function applyTranslations() {
  const lang = document.documentElement.lang || 'ar';
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
  // Update font
  if (lang === 'ar') {
    document.body.style.fontFamily = "'Tajawal','Cairo',system-ui,sans-serif";
  } else {
    document.body.style.fontFamily = "system-ui,-apple-system,'Segoe UI',Roboto,sans-serif";
  }
  // Update all elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (I18N[lang]?.[key]) {
      // Only update text nodes (don't overwrite SVG children for buttons with icons)
      const hasIconChild = Array.from(el.children).some(c => c.tagName === 'SVG' || c.classList?.contains('btn-icon') || c.classList?.contains('step-check') || c.classList?.contains('step-num'));
      if (hasIconChild) {
        // Find text node or span with btn-text
        const textEl = el.querySelector('.btn-text, .step-num, .step-label');
        if (textEl && !textEl.querySelector('svg')) {
          textEl.textContent = I18N[lang][key];
        }
      } else if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = I18N[lang][key];
      } else if (el.tagName === 'OPTION') {
        el.textContent = I18N[lang][key];
      } else {
        el.textContent = I18N[lang][key];
      }
    }
  });
  // Update lang attribute
  document.documentElement.lang = lang;
}
